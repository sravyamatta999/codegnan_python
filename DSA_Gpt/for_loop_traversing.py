#loop
'''a loop is used when we want to repeat something multiple times
'''

#for loop syntax
 #  for variable in something:
     #code to repeat
 
for i in range(5):
    print("Hello")

for i in range(2,6):
    print("sravya")
#2 is start and 6 is stop ,stop gives the o/p n-1.
    
for i in range(2,0,-1):
    print(i)
#2 is start value,0 is stop value but stop value will be not included and -1 is step value
    
for i in range(2,6,2):
    print(i)


